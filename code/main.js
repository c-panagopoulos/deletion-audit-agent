// Entry point: audits every request in dataset/deletion_requests.csv and writes output.csv at the repo root.
// Usage: node main.js [--input <csv>] [--output <csv>] [--traces <jsonl>] [--usage <md>]
//        node main.js --retry-unreadable   (re-read only visual files the last ingest could not read)
//        node main.js --cache-dir .cache-final --traces evaluation/final_traces.jsonl   (final run, fresh cache)
//        node main.js --cache-dir <dir> --backup-intents-from <dir>   (fresh vision, intents reused read-only from a cache)
//        node main.js --groq-model <id> --groq-reasoning-effort <low|none|...> --run-note "..."   (alternative intent model, ADR-030)
//        node main.js --help
import fs from 'node:fs';
import path from 'node:path';
import { readCsv, writeCsv } from './src/lib/csv.js';
import { dataset, REPO_ROOT, CODE_DIR } from './src/lib/paths.js';
import { createAgent } from './src/agent.js';
import { usageReport } from './src/usage.js';
import { verifyOutput } from './src/verifyOutput.js';
import { ingestEvidence, unreadableFileIds } from './src/ingest/index.js';
import { createLlm } from './src/llm/index.js';
import { groqAdapter } from './src/llm/groq.js';

if (process.argv.includes('--help') || process.argv.includes('-h')) {
  // Usage from the header comment; prints and exits before any data is read.
  console.log(fs.readFileSync(new URL(import.meta.url), 'utf8').split('\n').filter((l) => l.startsWith('//')).map((l) => l.slice(3)).join('\n'));
  process.exit(0);
}

const arg = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : fallback;
};
// --cache-dir <dir>: model-response cache for this run (the final run uses a fresh one, ADR-027).
if (arg('--cache-dir')) process.env.LLM_CACHE_DIR = path.resolve(arg('--cache-dir'));
// --groq-model / --groq-reasoning-effort: intent model and its reasoning setting (ADR-030); without them
// the defaults apply (openai/gpt-oss-120b, low). Flags rather than env so the command works on any OS.
if (arg('--groq-model')) process.env.GROQ_MODEL = arg('--groq-model');
if (arg('--groq-reasoning-effort')) process.env.GROQ_REASONING_EFFORT = arg('--groq-reasoning-effort');
// --backup-intents-from <dir>: backup final run (ADR-029). Vision runs fresh in --cache-dir; intents are
// read only from <dir>, never re-requested, and a missing intent stops the run.
if (arg('--backup-intents-from')) {
  process.env.LLM_TASK_CACHE_INTENT = path.resolve(arg('--backup-intents-from'));
  process.env.LLM_READONLY_TASKS = 'intent';
}

export async function run({ input, output, traces, usagePath }) {
  // Keep the organizers' row order; verifyOutput checks it against the template / request file.
  const requests = readCsv(input);
  const agent = await createAgent();
  const rows = [];
  const traceLines = [];
  for (const req of requests) {
    const r = await agent.auditCase(req);
    rows.push({ case_id: r.caseId, deletion_status: r.status, steps_json: JSON.stringify(r.steps) });
    traceLines.push(JSON.stringify(r.trace));
  }
  writeCsv(output, ['case_id', 'deletion_status', 'steps_json'], rows);
  if (traces) fs.writeFileSync(traces, traceLines.join('\n') + '\n');
  if (usagePath) {
    // State plainly where vision and intent answers came from (fresh in this run or reused from a cache).
    const freshOf = (task) => agent.usage.filter((u) => u.task === task && !u.cached).length;
    const reusedOf = (task) => agent.usage.filter((u) => u.task === task && u.cached).length;
    const origin = (task, label) => (reusedOf(task) && !freshOf(task) ? `${label} answers were reused from a cache produced earlier (see Provenance)`
      : freshOf(task) && !reusedOf(task) ? `${label} answers were produced fresh in this run`
      : `${label} answers: ${freshOf(task)} produced fresh, ${reusedOf(task)} reused from a cache (see Provenance)`);
    const mode = process.env.LLM_READONLY_TASKS?.includes('intent') || process.env.LLM_TASK_CACHE_VISUAL_EXTRACT
      ? ` **Mixed-provenance run:** ${origin('visual_extract', 'vision')}; ${origin('intent', 'intent')}${process.env.LLM_READONLY_TASKS?.includes('intent') ? ' and no intent call was made' : ''}. The "Cold run" columns give the full cost of producing every answer from an empty cache, using the token counts recorded when the cached answers were produced.`
      : '';
    // Which model made the intent decisions, with its generation settings (ADR-030).
    const intentModel = `Intent model: \`${groqAdapter.model()}\` (${Object.entries(groqAdapter.settings()).map(([k, v]) => `${k} ${v}`).join(', ')}).`;
    const runNote = arg('--run-note') ? ` ${arg('--run-note')}` : '';
    const note = `Generated by \`node main.js\` on ${new Date().toISOString()} for ${path.relative(CODE_DIR, input)}.${mode} ${intentModel}${runNote}`;
    fs.writeFileSync(usagePath, usageReport(agent.usage, { requests: requests.length, title: 'Token usage and cost — final full-dataset run', note }));
  }
  return rows;
}

if (import.meta.url === `file://${process.argv[1]}` && process.argv.includes('--retry-unreadable')) {
  // Re-read only the visual files the last ingest marked unreadable; successes go to the cache, so the
  // next full run picks them up without re-auditing anything now.
  const ids = unreadableFileIds();
  if (!ids.length) console.log('no unreadable files in the last ingest report');
  else {
    const { report } = await ingestEvidence({ llm: createLlm(), only: ids });
    for (const r of report) console.log(`${r.fileId} ${r.status} ${r.observations} observations ${r.error ?? ''}`.trim());
    if (report.some((r) => r.status === 'unreadable')) process.exitCode = 1;
  }
} else if (import.meta.url === `file://${process.argv[1]}`) {
  const input = arg('--input', dataset('deletion_requests.csv'));
  const output = arg('--output', path.join(REPO_ROOT, 'output.csv'));
  let rows;
  try {
    rows = await run({ input, output, traces: arg('--traces'), usagePath: arg('--usage', path.join(CODE_DIR, 'evaluation', 'usage_report.md')) });
  } catch (err) {
    if (!err.dailyQuota) throw err;
    // Clean stop (ADR-027): nothing is written, completed answers stay cached; rerun to resume.
    const hint = /read-only cache/.test(err.message)
      ? 'The backup run only reuses cached intents; produce the missing ones first or use the normal final run.'
      : 'Completed model answers are cached; run the same command again when the quota renews.';
    console.error(`STOPPED: ${err.message}\nNo output.csv was written. ${hint}`);
    process.exit(2);
  }
  const counts = rows.reduce((m, r) => ({ ...m, [r.deletion_status]: (m[r.deletion_status] ?? 0) + 1 }), {});
  console.log(`wrote ${rows.length} rows to ${output}`, counts);
  // File-level contract check on the file as written to disk (ADR-012). Only meaningful for the
  // official request file; custom inputs skip it.
  if (input === dataset('deletion_requests.csv')) {
    const check = verifyOutput(output);
    console.log(`verifyOutput: ${check.ok ? 'PASS' : 'FAIL'} (${check.rows} rows, order vs ${check.orderReference})`);
    for (const e of check.errors) console.log(`  - ${e}`);
    if (!check.ok) process.exitCode = 1;
  }
}
